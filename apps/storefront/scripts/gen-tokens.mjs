// Generates src/styles/tokens.css (Tailwind v4 theme) and src/components/brand/brand-svg.ts
// from packages/tokens/senova.json and the brand SVGs in fixtures/storefront.
// Run: pnpm tokens:gen
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const app = resolve(here, '..')
const repo = resolve(app, '../..')
const tokens = JSON.parse(readFileSync(resolve(repo, 'packages/tokens/senova.json'), 'utf8'))

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())
const px = (v) => (typeof v === 'number' ? `${v}px` : v)

const light = Object.entries(tokens.color).map(([k, v]) => `  --sn-${kebab(k)}: ${v};`)
const dark = Object.entries(tokens.colorDark).map(([k, v]) => `    --sn-${kebab(k)}: ${v};`)
const themeColors = Object.keys(tokens.color).map((k) => `  --color-${kebab(k)}: var(--sn-${kebab(k)});`)
const radius = Object.entries(tokens.radius).map(([k, v]) => `  --radius-${kebab(k)}: ${px(v)};`)
const motion = ['fast', 'base', 'slow'].map((k) => `  --sn-duration-${k}: ${tokens.motion[k]};`)
const grads = Object.entries(tokens.utilityGradients).flatMap(([k, [from, to]]) => [
  `  --sn-util-${k}-from: ${from};`,
  `  --sn-util-${k}-to: ${to};`,
])

const css = `/* Generated by scripts/gen-tokens.mjs from packages/tokens/senova.json. Do not edit by hand. */
:root {
${light.join('\n')}
${motion.join('\n')}
${grads.join('\n')}
  --sn-ease: ${tokens.motion.ease};
  color-scheme: light dark;
}

@media (prefers-color-scheme: dark) {
  :root {
${dark.join('\n')}
  }
}

@theme inline {
${themeColors.join('\n')}
${radius.join('\n')}
  --ease-senova: var(--sn-ease);
  --font-display: var(--font-bricolage), var(--font-be-vietnam), system-ui, sans-serif;
  --font-body: var(--font-be-vietnam), system-ui, -apple-system, 'Segoe UI', sans-serif;
}
`

const logo = readFileSync(resolve(repo, 'fixtures/storefront/logo-senova.svg'), 'utf8').trim()
const monogram = readFileSync(resolve(repo, 'fixtures/storefront/monogram-senova.svg'), 'utf8').trim()
// Plum becomes currentColor so one logo works on light, dark and plum backgrounds.
// The mask id gets a placeholder so several logos can share a page.
const logoInner = logo
  .replace(/^<svg[^>]*>/, '')
  .replace(/<\/svg>$/, '')
  .replaceAll('#5A2A4F', 'currentColor')
  .replaceAll('id="k1"', 'id="__ID__"')
  .replaceAll('url(#k1)', 'url(#__ID__)')
const logoViewBox = logo.match(/viewBox="([^"]+)"/)[1]

const ts = `// Generated by scripts/gen-tokens.mjs. Do not edit by hand.
export const LOGO_VIEWBOX = ${JSON.stringify(logoViewBox)}
export const LOGO_INNER = ${JSON.stringify(logoInner)}
export const MONOGRAM_SVG = ${JSON.stringify(monogram)}
`

mkdirSync(resolve(app, 'src/styles'), { recursive: true })
mkdirSync(resolve(app, 'src/components/brand'), { recursive: true })
writeFileSync(resolve(app, 'src/styles/tokens.css'), css)
writeFileSync(resolve(app, 'src/components/brand/brand-svg.ts'), ts)
console.log('tokens.css + brand-svg.ts generated')
